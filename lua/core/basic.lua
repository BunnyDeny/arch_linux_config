-- 显示行号
vim.opt.number = true 

-- 显示相对行号
vim.opt.relativenumber = true

-- 高亮显示当前行
vim.opt.cursorline = true

-- 在第 80 列画一条竖直的参考线
vim.opt.colorcolumn = "80"

-- tab转换为空格
vim.opt.expandtab = true

-- 每个tab相当于4个空格
vim.opt.tabstop = 4

-- 会将 shiftwidth 设置为和 tabstop 相同的值。
vim.opt.shiftwidth = 0

-- 当其他程序修改了正打开的文件，自动加载文件最新内容
vim.opt.autoread = true

